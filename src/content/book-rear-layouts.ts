export interface InkField {
  x: number;
  y: number;
  width: number;
  height: number;
  color: string;
  tilt: number;
}

export interface PrintBlock {
  x: number;
  y: number;
  width: number;
  height: number;
  lines: number;
  color?: string;
  alignment: CanvasTextAlign;
}

export interface DisplayLine {
  text: string;
  x: number;
  baseline: number;
  width: number;
  size: number;
  alignment: CanvasTextAlign;
  color?: string;
}

interface PriceBox {
  x: number;
  y: number;
  width: number;
  height: number;
  color: string;
  supplement?: string;
  alignModules?: boolean;
}

export interface RearLayout {
  paper: string;
  fade?: { start: number; bottom: string };
  ink: string;
  serif?: boolean;
  boldText?: boolean;
  fields?: InkField[];
  blocks: PrintBlock[];
  headings: DisplayLine[];
  barcode?: PriceBox;
}

const field = (
  x: number,
  y: number,
  width: number,
  height: number,
  color: string,
  tilt = 0,
): InkField => ({ x, y, width, height, color, tilt });
const area = (
  x: number,
  y: number,
  width: number,
  height: number,
  lines: number,
  color?: string,
  alignment: CanvasTextAlign = 'left',
): PrintBlock => ({ x, y, width, height, lines, color, alignment });
const center = (
  x: number,
  y: number,
  width: number,
  height: number,
  lines: number,
  color?: string,
) => area(x, y, width, height, lines, color, 'center');
const title = (
  text: string,
  x: number,
  baseline: number,
  width: number,
  size: number,
  alignment: CanvasTextAlign = 'left',
  color?: string,
): DisplayLine => ({ text, x, baseline, width, size, alignment, color });
const bars = (
  x: number,
  y: number,
  width: number,
  height: number,
  color: string,
  supplement?: string,
): PriceBox => ({ x, y, width, height, color, supplement });

