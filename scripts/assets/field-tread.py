import math


def build_tread(part, hand, foot, rubber, yellow, ink):
    bounds = [
        (25, 220, 225),
        (30, 191, 272),
        (45, 166, 301),
        (65, 146, 325),
        (95, 124, 346),
        (126, 109, 358),
        (162, 96, 369),
        (204, 81, 375),
        (245, 74, 379),
        (283, 77, 376),
        (323, 84, 367),
        (365, 96, 351),
        (403, 119, 331),
        (434, 141, 320),
        (466, 155, 317),
        (493, 160, 323),
        (525, 155, 337),
        (559, 150, 351),
        (596, 149, 364),
        (635, 147, 374),
        (662, 149, 377),
        (678, 155, 377),
        (715, 161, 372),
        (747, 176, 357),
        (770, 197, 336),
        (785, 217, 317),
        (794, 245, 281),
        (796, 257, 263),
    ]

    def coord(x, y, z):
        x = max(25.01, min(795.99, x))
        k = next(k for k, p in enumerate(bounds) if p[0] >= x)
        a, b = bounds[k - 1 : k + 1]
        t = (x - a[0]) / (b[0] - a[0])
        low = a[1] + (b[1] - a[1]) * t
        high = a[2] + (b[2] - a[2]) * t
        return foot(
            139 - 269 * (x - 25) / 771,
            hand * max(-0.995, min(0.995, 2 * (y - low) / (high - low) - 1)),
            z,
        )

    front = part("Vibram forefoot traction")
    heel = part("Vibram heel brake tread")
    shank = part("Vibram shank and molded badge")

    def pad(obj, poly, low=0.08, high=5.8, mat=rubber):
        cx = sum(x for x, y in poly) / len(poly)
        cy = sum(y for x, y in poly) / len(poly)
        rows = [
            [coord(cx + (x - cx) * scale, cy + (y - cy) * scale, z) for x, y in poly]
            for scale, z in [
                (1, high),
                (0.987, high - 1),
                (0.907, low + 0.7),
                (0.862, low),
            ]
        ]
        obj.rings(rows, mat, False)

    def tooth(x, y, w, h, lean, style):
        if style == 0:
            points = [
                (-0.5, -0.44),
                (-0.25, -0.53),
                (0.43, -0.49),
                (0.50, 0.19),
                (0.22, 0.48),
                (-0.40, 0.5),
                (-0.54, 0.12),
            ]
        elif style == 1:
            points = [
                (-0.52, -0.26),
                (-0.11, -0.54),
                (0.49, -0.42),
                (0.52, -0.05),
                (0.28, 0.47),
                (-0.32, 0.52),
                (-0.48, 0.15),
            ]
        else:
            points = [
                (-0.48, -0.36),
                (-0.08, -0.55),
                (0.41, -0.50),
                (0.48, 0.25),
                (0.11, 0.51),
                (-0.48, 0.41),
            ]
        return [(x + px * w + lean * py, y + py * h) for px, py in points]

    edges = [
        (54, 170, 290),
        (81, 149, 315),
        (110, 133, 334),
        (142, 116, 349),
        (178, 106, 358),
        (215, 93, 365),
        (258, 91, 366),
        (300, 92, 357),
        (343, 104, 343),
        (378, 117, 326),
        (405, 140, 304),
    ]
    for i, (x, top, bottom) in enumerate(edges):
        w = 18 + min(13, i * 2.2) if i < 8 else 26
        if i:
            pad(
                front,
                tooth(x, top + 9, w, 38 + min(10, i * 2), -12, (i + 1) % 3),
            )
        pad(
            front,
            tooth(x + 3, bottom - 10, w + 1, 39 + min(9, i * 2), 11, i % 3),
        )
    paths = [
        [
            (60, 210, 18, 27),
            (88, 200, 22, 34),
            (115, 191, 21, 38),
            (151, 178, 24, 39),
            (189, 165, 26, 38),
            (231, 164, 26, 43),
            (276, 167, 28, 39),
            (321, 184, 24, 40),
            (355, 201, 22, 41),
            (386, 207, 23, 37),
        ],
        [
            (58, 257, 15, 24),
            (89, 254, 23, 28),
            (119, 248, 27, 34),
            (155, 241, 30, 38),
            (201, 226, 29, 45),
            (244, 222, 31, 45),
            (286, 222, 29, 45),
            (328, 237, 28, 40),
            (361, 250, 21, 33),
            (391, 245, 19, 28),
        ],
        [
            (153, 296, 30, 32),
            (195, 293, 24, 36),
            (236, 290, 29, 38),
            (279, 284, 28, 38),
            (318, 280, 30, 37),
            (354, 284, 25, 28),
        ],
    ]
    for row, path in enumerate(paths):
        for i, (x, y, w, h) in enumerate(path):
            poly = tooth(x, y, w, h, 4 * (i % 3 - 1), i % 3)
            pad(front, poly)
            if (i + row) % 3 == 1:
                front.pipe(
                    [
                        coord(x - w * 0.34, y - h * 0.29, 0.01),
                        coord(x + w * 0.10, y + h * 0.14, 0.01),
                        coord(x + w * 0.35, y + h * 0.25, 0.01),
                    ],
                    0.24,
                    ink,
                    5,
                    0.32,
                )
    for k in range(3):
        x = 29 + k * 4.5
        pad(
            front,
            [
                (x + 1, 208 - 8 * k),
                (x + 3, 185 - 11 * k),
                (x + 5, 183 - 10 * k),
                (x + 4, 225),
                (x + 5, 274 + 3 * k),
                (x, 270 + 1.5 * k),
            ],
            low=0.8,
        )
    pad(
        shank,
        [
            (401, 304),
            (422, 251),
            (435, 184),
            (454, 177),
            (486, 179),
            (502, 221),
            (520, 324),
            (490, 310),
            (451, 305),
        ],
        2.5,
        5.7,
    )
    badge = [
        (448, 222),
        (459, 214),
        (477, 214),
        (486, 222),
        (495, 259),
        (482, 281),
        (469, 285),
        (455, 273),
    ]
    pad(shank, badge, 1.0, 3.3, yellow)
    shank.label(
        "Vibram",
        4.8,
        lambda x, y: coord(472 + 2.3 * y + 0.53 * x, 249 + 2.6 * x, 0.84),
        ink,
        True,
    )
    for i, (x, top, low) in enumerate(
        [
            (517, 160, 332),
            (549, 151, 347),
            (585, 150, 359),
            (623, 149, 368),
            (649, 150, 372),
        ]
    ):
        pad(
            heel,
            [
                (x - 7, top + 3),
                (x + 15, top + 1),
                (x + 14, top + 46),
                (x + 4, top + 41),
                (x - 9, top + 30),
            ],
        )
        pad(
            heel,
            [
                (x - 5, low - 45),
                (x + 9, low - 52),
                (x + 19, low - 35),
                (x + 18, low),
                (x + 1, low - 1),
                (x - 8, low - 14),
            ],
        )
        if i in [0, 2, 3]:
            pad(heel, tooth(x + 3, 246 + i * 3, 25, 51, 14, 1))
    for i in range(20):
        y = 153 + i * 11.35
        x = 666 + 2.2 * math.sin((y - 150) * 0.020)
        pad(heel, [(x - 3, y), (x + 2, y), (x + 4, y + 6), (x - 2, y + 7)], 2.45, 5.6)
    for i, (x, lo, hi) in enumerate(
        [
            (687, 155, 374),
            (711, 160, 373),
            (736, 168, 364),
            (758, 179, 348),
            (775, 199, 331),
            (787, 218, 308),
        ]
    ):
        w = [20, 21, 20, 14, 10, 8][i]
        middle = 240 + (x - 680) * 0.28 + 7 * math.sin((x - 674) * 0.033)
        upper = [
            (x - w * 0.5 + 4, lo + 2),
            (x + w * 0.5 + 2, lo + 4),
            (x + w * 0.5 - 7, middle - 2),
            (x - w * 0.5 - 5, middle - 10),
        ]
        lower = [
            (x - w * 0.5 - 4, middle + 2),
            (x + w * 0.5 - 4, middle + 10),
            (x + w * 0.5 + 4, hi - 3),
            (x - w * 0.5 + 3, hi - 2),
        ]
        pad(heel, upper)
        pad(heel, lower)
        if i in [0, 1, 2]:
            for mid_y in [lo * 0.5 + middle * 0.5, hi * 0.5 + middle * 0.5]:
                heel.pipe(
                    [
                        coord(x - w * 0.38, mid_y - 3, 0.03),
                        coord(x + w * 0.35, mid_y + 3, 0.03),
                    ],
                    0.33,
                    ink,
                    5,
                    0.42,
                )
